import type { Metadata } from "next";
import { Inter, JetBrains_Mono } from "next/font/google";
import "./globals.css";
import { ThemeProvider } from "@/components/ThemeProvider";

// Replaces the render-blocking `@import url('https://fonts.googleapis.com/...')`
// that used to live at the top of globals.css. next/font self-hosts the font
// files at build time (no third-party request at runtime), inlines
// size-adjusted @font-face fallback metrics to avoid layout shift, and
// exposes each family as a CSS variable applied on <html> below — same
// weights/subsets as the old Google Fonts URL requested.
const inter = Inter({
  subsets: ["latin"],
  weight: ["400", "500", "600", "700"],
  variable: "--font-inter",
  display: "swap",
});

const jetbrainsMono = JetBrains_Mono({
  subsets: ["latin"],
  weight: ["400", "500"],
  variable: "--font-jetbrains-mono",
  display: "swap",
});

export const metadata: Metadata = {
  title: "ClinKit",
  description: "Your clinical data analyst toolkit",
  icons: { icon: "/favicon.svg" },
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html
      lang="en"
      className={`dark ${inter.variable} ${jetbrainsMono.variable}`}
      suppressHydrationWarning
    >
      <body>
        <ThemeProvider>{children}</ThemeProvider>
      </body>
    </html>
  );
}
